export function useI18n() {
    const { lang } = useLanguage();
    return useMemo(() => {
        return function t(key) {
            return messages[lang]?.[key] ?? messages.ka[key] ?? messages.en[key] ?? key;
        };
    }, [lang]);
}

export function translateStatus(status, langCode) {
    const key = `status.${status}`;
    return messages[langCode]?.[key] ?? messages.ka[key] ?? messages.en[key] ?? status;
}
